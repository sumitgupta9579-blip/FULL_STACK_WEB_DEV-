let percentage = 72;
if(percentage < 0 && percentage > 100) console.log(percentage,"Invalid Percentage !");
else{
    if(percentage >=90) console.log(percentage,"A Grade");
    else if (percentage >=90) console.log(percentage,"A Grade");
    else if (percentage >=80) console.log(percentage,"B Grade");
    else if (percentage >=70) console.log(percentage,"C Grade");
    else if (percentage >=60) console.log(percentage,"D Grade");
    else if (percentage >=40) console.log(percentage,"E Grade");
    else console.log(percentage,"Fail");
}